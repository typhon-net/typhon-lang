using System.Diagnostics;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;

namespace Typhon.Cli;

/// <summary>A NuGet package a program asks for with "#:package Name@Version" (Version "*" for the latest).</summary>
internal sealed record PackageRef(string Id, string Version)
{
    public override string ToString() => Id + "@" + Version;
}

/// <summary>
/// NuGet packages for programs without a project: "#:package Name@Version" lines (the directive of .NET's file-based apps;
/// a comment to Python). The packages are restored once with `dotnet restore` of a generated project, which resolves their
/// dependencies the way NuGet does, into a cache keyed by the package list; the program compiles against their reference
/// assemblies and runs with their implementation assemblies.
/// </summary>
internal static class Packages
{
    static readonly Regex Directive = new(@"^#:package[ \t]+([A-Za-z0-9_.\-]+)(?:@([^\s]+))?[ \t]*$", RegexOptions.Multiline);

    /// <summary>The #:package directives of a source file.</summary>
    public static IEnumerable<PackageRef> Directives(string source) =>
        Directive.Matches(source).Select(m => new PackageRef(m.Groups[1].Value, m.Groups[2].Success ? m.Groups[2].Value : "*"));

    /// <summary>The assemblies of the restored packages: what the program compiles against, and what it loads when it runs.</summary>
    public sealed record Assemblies(List<string> Compile, List<string> Runtime);

    static string Tfm => $"net{Environment.Version.Major}.{Environment.Version.Minor}";

    /// <summary>
    /// The packages' assemblies, restoring them first when this package list was not restored before. Null with an error
    /// message when the restore fails (no network, a package or version that does not exist, no .NET SDK).
    /// </summary>
    public static Assemblies? Restore(IReadOnlyCollection<PackageRef> packages, out string? error)
    {
        error = null;
        var sorted = packages.Select(p => p.ToString()).Distinct(StringComparer.OrdinalIgnoreCase).OrderBy(p => p, StringComparer.OrdinalIgnoreCase).ToList();
        string key = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(Tfm + "\n" + string.Join("\n", sorted))))[..20].ToLowerInvariant();
        string dir = Path.Combine(ScriptCache.Root, "packages", key);
        string resolved = Path.Combine(dir, "assemblies.txt");
        // a floating version (*) is re-resolved once a day; a fixed one stays restored
        bool floating = packages.Any(p => p.Version.Contains('*'));
        if (File.Exists(resolved) && (!floating || DateTime.UtcNow - File.GetLastWriteTimeUtc(resolved) < TimeSpan.FromDays(1)) &&
            Read(resolved) is Assemblies cached)
            return cached;

        Directory.CreateDirectory(dir);
        var items = packages.Select(p => $"""    <PackageReference Include="{p.Id}" Version="{p.Version}" />""");
        File.WriteAllText(Path.Combine(dir, "restore.csproj"), $"""
            <Project Sdk="Microsoft.NET.Sdk">
              <!-- Generated by typhon for #:package directives: restored, never built. -->
              <PropertyGroup>
                <TargetFramework>{Tfm}</TargetFramework>
                <ImportDirectoryBuildProps>false</ImportDirectoryBuildProps>
                <ImportDirectoryBuildTargets>false</ImportDirectoryBuildTargets>
              </PropertyGroup>
              <ItemGroup>
            {string.Join("\n", items)}
              </ItemGroup>
            </Project>
            """);
        Console.Error.WriteLine($"[typhon] restoring {string.Join(", ", sorted)} ...");
        var psi = new ProcessStartInfo(SharedFrameworks.DotnetExecutable)
        {
            RedirectStandardOutput = true, RedirectStandardError = true, UseShellExecute = false, WorkingDirectory = dir,
        };
        foreach (var a in new[] { "restore", "restore.csproj", "-nologo", "-v", "q" }) psi.ArgumentList.Add(a);
        psi.Environment["DOTNET_NOLOGO"] = "1";
        psi.Environment["DOTNET_CLI_TELEMETRY_OPTOUT"] = "1";
        string output;
        try
        {
            using var proc = Process.Start(psi)!;
            var stdout = proc.StandardOutput.ReadToEndAsync();
            var stderr = proc.StandardError.ReadToEndAsync();
            proc.WaitForExit();
            output = stdout.Result + stderr.Result;
            if (proc.ExitCode != 0)
            {
                // (from "error": the generated project's path is noise)
                var lines = output.Split('\n').Where(l => l.Contains("error")).Select(l => l.Trim()).Select(l => l.Substring(Math.Max(0, l.IndexOf("error", StringComparison.Ordinal)))).Distinct().Take(5);
                error = $"typhon: restoring {string.Join(", ", sorted)} failed:\n  " + string.Join("\n  ", lines);
                return null;
            }
        }
        catch (System.ComponentModel.Win32Exception)
        {
            error = "typhon: #:package needs the .NET SDK (dotnet restore), which was not found";
            return null;
        }
        var assemblies = FromAssetsFile(Path.Combine(dir, "obj", "project.assets.json"), out error);
        if (assemblies == null) return null;
        File.WriteAllLines(resolved, assemblies.Compile.Select(p => "compile " + p).Concat(assemblies.Runtime.Select(p => "runtime " + p)));
        return assemblies;
    }

    static Assemblies? Read(string file)
    {
        var compile = new List<string>();
        var runtime = new List<string>();
        foreach (var line in File.ReadAllLines(file))
        {
            if (line.StartsWith("compile ")) compile.Add(line[8..]);
            else if (line.StartsWith("runtime ")) runtime.Add(line[8..]);
        }
        // a cleared NuGet cache: restore again
        return compile.Concat(runtime).All(File.Exists) ? new Assemblies(compile, runtime) : null;
    }

    /// <summary>The compile and runtime assemblies NuGet chose for this framework (project.assets.json of the restore).</summary>
    static Assemblies? FromAssetsFile(string path, out string? error)
    {
        error = null;
        try
        {
            using var doc = JsonDocument.Parse(File.ReadAllText(path));
            var root = doc.RootElement;
            string folder = root.GetProperty("packageFolders").EnumerateObject().First().Name;
            var libraries = root.GetProperty("libraries");
            var target = root.GetProperty("targets").EnumerateObject().First(t => !t.Name.Contains('/')).Value;
            var compile = new List<string>();
            var runtime = new List<string>();
            foreach (var package in target.EnumerateObject())
            {
                if (package.Value.TryGetProperty("type", out var type) && type.GetString() != "package") continue;
                string libPath = libraries.GetProperty(package.Name).GetProperty("path").GetString()!;
                void Collect(string kind, List<string> into)
                {
                    if (!package.Value.TryGetProperty(kind, out var assets)) return;
                    foreach (var asset in assets.EnumerateObject())
                        if (asset.Name.EndsWith(".dll", StringComparison.OrdinalIgnoreCase)) // ("_._": nothing for this framework)
                            into.Add(Path.GetFullPath(Path.Combine(folder, libPath, asset.Name)));
                }
                Collect("compile", compile);
                Collect("runtime", runtime);
            }
            return new Assemblies(compile, runtime);
        }
        catch (Exception e) when (e is IOException || e is JsonException || e is KeyNotFoundException || e is InvalidOperationException)
        {
            error = $"typhon: could not read the restored packages ({path}): {e.Message}";
            return null;
        }
    }
}
