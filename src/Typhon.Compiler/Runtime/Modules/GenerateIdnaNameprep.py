"""Generate RFC 3454 Nameprep tables from CPython 3.15's stringprep module."""

import base64
import gzip
from pathlib import Path
import stringprep
import struct
import textwrap


maps = {}
ranges = []
prohibited = (stringprep.in_table_c12, stringprep.in_table_c22, stringprep.in_table_c3,
              stringprep.in_table_c4, stringprep.in_table_c5, stringprep.in_table_c6,
              stringprep.in_table_c7, stringprep.in_table_c8, stringprep.in_table_c9)
for point in range(0x110000):
    character = chr(point)
    mapping = '' if stringprep.in_table_b1(character) else stringprep.map_table_b2(character)
    if mapping != character:
        maps[point] = mapping.encode('utf-8')
    if any(check(character) for check in prohibited):
        if ranges and ranges[-1][1] == point - 1:
            ranges[-1][1] = point
        else:
            ranges.append([point, point])

packed = bytearray(struct.pack('<II', len(maps), len(ranges)))
for point, mapping in maps.items():
    packed += struct.pack('<IH', point, len(mapping)) + mapping
for start, end in ranges:
    packed += struct.pack('<II', start, end)
encoded = base64.b64encode(gzip.compress(packed, mtime=0)).decode('ascii')
lines = ' +\n'.join(f'            "{line}"' for line in textwrap.wrap(encoded, 112))
output = Path(__file__).with_name('Codecs.IdnaData.Generated.cs')
output.write_text(f'''// Generated by GenerateIdnaNameprep.py from CPython 3.15 stringprep's RFC 3454 tables.
// See CPython-LICENSE.txt and Unicode-LICENSE.txt for the original data licenses.
#nullable enable
#pragma warning disable CS8981

namespace Typhon.Stdlib
{{
    internal static partial class codecs
    {{
        const string IdnaNameprepTables =
{lines};
    }}
}}
''', encoding='utf-8')
