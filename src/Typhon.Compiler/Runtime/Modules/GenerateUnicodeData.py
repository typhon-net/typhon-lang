"""Generate the versioned Unicode character properties used by Typhon.

Run with CPython 3.15. The encoding uses little-endian numbers and
length-prefixed UTF-8 strings, compressed with gzip.
The source data is the Unicode Character Database. See Unicode-LICENSE.txt.
"""

import base64
import gzip
import io
import struct
import textwrap
import unicodedata
from pathlib import Path


def pack_database(database, include_compositions):
    output = io.BytesIO()

    def integer(value):
        output.write(struct.pack("<i", value))

    def character_string(value):
        encoded = value.encode("utf-8")
        integer(len(encoded))
        output.write(encoded)

    def int_list(values):
        integer(len(values))
        for value in values:
            integer(value)

    properties = {}
    ranges = []
    decompositions = {}
    numeric = {}
    canonical = {}
    compatible = {}
    compositions = {}
    last = None
    for cp in range(0x110000):
        ch = chr(cp)
        cat = database.category(ch)
        record = (cat, database.bidirectional(ch), database.combining(ch),
                  database.east_asian_width(ch), database.mirrored(ch))
        if record != last:
            ranges.append((cp, properties.setdefault(record, len(properties))))
            last = record

        raw_decomposition = database.decomposition(ch)
        if raw_decomposition:
            decompositions[cp] = raw_decomposition

        number = database.numeric(ch, None)
        if number is not None:
            numeric[cp] = (database.decimal(ch, -1), database.digit(ch, -1), number)

        # Hangul algorithmic mappings are handled by the reader.
        if 0xAC00 <= cp < 0xD7A4:
            continue
        normalized = database.normalize("NFD", ch)
        compatibility = database.normalize("NFKD", ch)
        if normalized != ch:
            canonical[cp] = list(map(ord, normalized))
        if compatibility != normalized:
            compatible[cp] = list(map(ord, compatibility))

        pair = raw_decomposition.split()
        if include_compositions and len(pair) == 2 and not pair[0].startswith("<"):
            first, second = map(lambda value: int(value, 16), pair)
            if database.normalize("NFC", chr(first) + chr(second)) == ch:
                compositions[first, second] = cp

    integer(len(properties))
    for cat, bidi, combining, width, mirrored in properties:
        character_string(cat)
        character_string(bidi)
        output.write(bytes([combining]))
        character_string(width)
        output.write(bytes([mirrored]))
    integer(len(ranges))
    for start, index in ranges:
        integer(start)
        integer(index)
    integer(len(decompositions))
    for codepoint, value in decompositions.items():
        integer(codepoint)
        character_string(value)
    integer(len(numeric))
    for codepoint, (decimal, digit, value) in numeric.items():
        integer(codepoint)
        output.write(struct.pack("<bbd", decimal, digit, value))
    for mapping in (canonical, compatible):
        integer(len(mapping))
        for codepoint, value in mapping.items():
            integer(codepoint)
            int_list(value)
    integer(len(compositions))
    for (first, second), value in sorted(compositions.items()):
        integer(first)
        integer(second)
        integer(value)
    return base64.b64encode(gzip.compress(output.getvalue(), mtime=0)).decode("ascii")


header = """// Generated by GenerateUnicodeData.py. See Unicode-LICENSE.txt for the data license.
#nullable enable
#pragma warning disable CS8981
namespace Typhon.Stdlib
{
    internal static partial class unicodedata
    {
"""
source = header
for name, database in [("CurrentData", unicodedata), ("LegacyData", unicodedata.ucd_3_2_0)]:
    assert database.unidata_version == ("17.0.0" if name == "CurrentData" else "3.2.0")
    encoded = pack_database(database, include_compositions=name == "CurrentData")
    source += f'        const string {name} =\n'
    source += " +\n".join(f'            "{line}"' for line in textwrap.wrap(encoded, 120))
    source += ";\n\n"
source += "    }\n}\n"
Path(__file__).with_name("UnicodeData.Generated.cs").write_text(source, encoding="utf-8", newline="\n")


def pack_grapheme_properties():
    # The numeric values follow the enums in UnicodeData.Graphemes.cs.
    grapheme = {name: i for i, name in enumerate((
        "Other", "CR", "LF", "Control", "Extend", "ZWJ", "Regional_Indicator",
        "Prepend", "SpacingMark", "L", "V", "T", "LV", "LVT",
    ))}
    indic = {"None": 0, "Consonant": 1, "Extend": 2, "Linker": 3}
    runs = io.BytesIO()
    previous = None
    for cp in range(0x110000):
        character = chr(cp)
        flags = (grapheme[unicodedata.grapheme_cluster_break(character)]
                 | indic[unicodedata.indic_conjunct_break(character)] << 4
                 | int(unicodedata.extended_pictographic(character)) << 6)
        if flags != previous:
            runs.write(struct.pack("<IB", cp, flags))
            previous = flags
    data = runs.getvalue()
    return base64.b64encode(gzip.compress(struct.pack("<i", len(data) // 5) + data, mtime=0)).decode("ascii")


graphemes = " +\n".join(f'            "{line}"' for line in textwrap.wrap(pack_grapheme_properties(), 120))
source = header + "        const string GraphemeData =\n" + graphemes + ";\n    }\n}\n"
Path(__file__).with_name("UnicodeData.Graphemes.Generated.cs").write_text(source, encoding="utf-8", newline="\n")
