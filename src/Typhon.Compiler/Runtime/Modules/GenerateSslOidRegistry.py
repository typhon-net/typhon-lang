"""Export the OpenSSL OID registry exposed by the pinned CPython oracle."""

import _ssl
from pathlib import Path
import sys


if sys.version_info[:3] != (3, 15, 2) or _ssl.OPENSSL_VERSION.split()[1] != "3.5.9":
    raise SystemExit("Run with CPython 3.15.2 linked to OpenSSL 3.5.9")

entries = []
for nid in range(1, 8192):
    try:
        n, short_name, long_name, oid = _ssl.nid2obj(nid)
    except ValueError:
        continue

    # Duplicate names and numeric identifiers may resolve to a different NID.
    lookups = "".join(
        flag for flag, text, names in (("S", short_name, True), ("L", long_name, True), ("O", oid, False))
        if text is not None and _ssl.txt2obj(text, name=names)[0] == nid
    )
    fields = (str(n), short_name, long_name, oid or "", lookups or "-")
    assert all(not any(character in field for character in "\r\n\t") and '"""' not in field for field in fields)
    entries.append("\t".join(fields))

assert len(entries) == 1477
header = '''// Copyright 1995-2026 The OpenSSL Project Authors. All Rights Reserved.
// Licensed under the Apache License, Version 2.0. See OpenSSL-OID-LICENSE.txt.
// Object registry data from OpenSSL 3.5.9, exported through CPython 3.15.2.
// https://github.com/openssl/openssl/tree/openssl-3.5.9/crypto/objects
// Generated by GenerateSslOidRegistry.py.

namespace Typhon.Stdlib
{
    internal static partial class _ssl
    {
        const string OidRegistryData = """
'''
output = Path(__file__).with_name("Ssl.OidRegistry.Generated.cs")
output.write_text(header + "\n".join(entries) + '\n""";\n    }\n}\n', encoding="utf-8", newline="\n")
