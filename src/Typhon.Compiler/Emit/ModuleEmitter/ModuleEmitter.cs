        ClassContext _cls;
        readonly Stack<Dictionary<string, string>> _lambdaParams = new Stack<Dictionary<string, string>>();
        int _tmp;
        string _path;

        /// <summary>Big-int mode: Python's int is BigInteger (see ProjectContext.BigInts); else a checked long.</summary>
        bool _big => _p.BigInts;
        /// <summary>The C# type of Python's int.</summary>
        string IntT => _p.BigInts ? TypeInference.BigInt : "long";

        public ModuleEmitter(ModuleInfo module, ProjectContext project, List<TyDiagnostic> diags, bool dryRun = false)
        {
            _m = module; _p = project; _diags = diags; _r = ResolverFor(module, project); _path = module.Path; _dry = dryRun;
        }


        void Report(Node at, string id, Severity sev, string msg)
        {
            _diags.Add(new TyDiagnostic { Id = id, Severity = sev, Message = msg, Path = _path, Line = at?.Line ?? 1, Col = at?.Col ?? 1 });
        }

        void Error(Node at, string msg) => Report(at, "TY0002", Severity.Error, msg);
        void Unsupported(Node at, string what) => Report(at, "TY0003", Severity.Error, what + " is not supported in Typhon yet");

        /// <summary>Every implicit fallback to 'dynamic' goes through here (TypeScript-style noImplicitAny).</summary>
        /// <summary>
        /// Emitting code that exists only for calls the compiler cannot see (a method's late-bound version beside its typed
        /// overloads): its dynamic parameters and locals are expected, not something to report.
        /// </summary>
        bool _quietDynamic;

        string ImplicitDynamic(Node at, string what)
        {
            if (_quietDynamic) return "dynamic";
            if (_p.TypeMode == TypeMode.Strict)
                Report(at, "TY1001", Severity.Error, $"cannot infer the type of {what}; add a type annotation (or annotate it as 'Any' to opt into dynamic typing)");
            else if (_p.TypeMode == TypeMode.Warn)
                Report(at, "TY1001", Severity.Warning, $"{what} is implicitly dynamic (late-bound, slower); add a type annotation");
            return "dynamic";
        }

        void LineDirective(Node n)
        {
            if (n != null && n.Line > 0) _w.Raw("#line " + n.Line + " \"" + _path + "\"");
        }

        string PythonModuleName => _m.IsMainModule && (_p.MainModule == null || _p.MainModule == _m.Name) ? "__main__" : _m.Name;


        public string Emit()
        {
            // GDScript has no access control: every member of a .gd module is public (Godot calls _process & co.)
            bool savedPublic = t_allPublic;
            t_allPublic = _m.IsGdScript;
            try { return EmitModule(); }
            finally { t_allPublic = savedPublic; }
        }

        string EmitModule()
        {
            if (_m.RuntimeCodeMode != null) LowerRuntimeImports(_m.Ast.Body);
            ResolveFailingImports(_m.Ast.Body);
            MaterializeNativeTypeExports(_m.Ast.Body);
            RemoveResolvedImportBindings();
            foreach (var n in AllNodes(_m.Ast.Body))
            {
                if (n is ImportStmt i) ProcessImport(i);
                else if (n is ImportFromStmt f) ProcessImportFrom(f);
            }

            _w.Raw("// <auto-generated>");
            _w.Raw("//   Generated by the Typhon compiler from " + System.IO.Path.GetFileName(_path) + ". Do not edit.");
            _w.Raw("// </auto-generated>");
            _w.Raw("#pragma warning disable CS1718, CS0183, CS0184, CS0162, CS0164, CS0168, CS0219, CS8321, CS1998, CS0105, CS0659, CS0660, CS0661, CS8981, CS1591");
            _w.Raw("#nullable enable annotations");
            _w.Line("using System;");
            _w.Line("using System.Collections.Generic;");
            _w.Line("using System.Linq;");
            _w.Line("using System.Threading.Tasks;");
            _w.Line("using static global::Typhon.Runtime.Builtins;");
            _w.Line("using static global::Typhon.Runtime.DictGetStruct;");
            _w.Line("using static global::Typhon.Runtime.DictGetClass;");
            foreach (var u in _usingLines.Distinct()) _w.Line(u);
            _w.Line();

            // return types of module-level functions feed the local type inference
            foreach (var f in _m.Ast.Body.OfType<FunctionDef>())
                if (f.Returns != null && !TypeInference.IsBareContainer(f.Returns) && f.TypeParams.Count == 0 && !AstWalker.ContainsOutsideNestedScopes(f.Body, n => n is YieldExpr))
                    _funcReturnTypes[f.Name] = AnnotatedCallResult(f);

            bool hasNs = !string.IsNullOrEmpty(_m.Namespace);
            if (hasNs) { _w.Line("namespace " + EscapeDottedName(_m.Namespace)); _w.Open(); }

            var body = _m.Ast.Body;
            // a GDScript module: the script class is a top-level class (Godot's script classes must be), which sees the
            // module's static class (its inner classes) through a using static
            if (GdScriptClass != null) _w.Line($"using static {ModuleClassName(_m)};");
            EmitDocComment(body);
            LineDirective(body.FirstOrDefault());
            if (!_m.IsGdScript)
            {
                _w.Line($"[global::Typhon.Runtime.PySource({CsString(_path)}, {CsString(PythonModuleName)}, doc: {ModuleDocLiteral(body)})]");
            }
            _w.Line("public static partial class " + Esc(_m.ClassName));
            _w.Open();
            EmitModuleBody(body);
            EmitAnnotationsMap(body);
            _w.Close();
            if (GdScriptClass != null) { _w.Line(); EmitClass(GdScriptClass); }

            if (hasNs) _w.Close();
            _w.Raw("#line default");
            return _w.ToString();
        }

        static IEnumerable<Node> AllNodes(object root)
        {
            var list = new List<Node>();
            AstWalker.VisitAll(root, list.Add);
            return list;
        }

        static bool IsMainGuard(Stmt s)
        {
            if (!(s is IfStmt i) || !(i.Test is CompareExpr c) || c.Ops.Count != 1 || c.Ops[0] != "==") return false;
            bool IsName(Expr e) => e is NameExpr n && n.Id == "__name__";
            bool IsMain(Expr e) => e is ConstExpr k && k.Kind == ConstKind.Str && k.Str == "__main__";
            return (IsName(c.Left) && IsMain(c.Comparators[0])) || (IsMain(c.Left) && IsName(c.Comparators[0]));
        }

        static string ModuleDocLiteral(List<Stmt> body) =>
            body.FirstOrDefault() is ExprStmt { Value: ConstExpr { Kind: ConstKind.Str } text } ? CsString(text.Str) : "null";

        void EmitModuleBody(List<Stmt> body)
        {
            bool isMainModule = _m.IsMainModule && (_p.MainModule == null || _p.MainModule == _m.Name);
            bool isEntryModule = isMainModule || _p.MainModule == _m.Name;
            bool runtimeCode = _m.RuntimeCodeMode != null;
            if (!_m.IsGdScript) FindIdentityTuples(body);
            if (runtimeCode)
            {
                _m.RuntimeBindings.UnionWith(_m.Globals);
                var moduleLocals = LocalsAnalyzer.Analyze(body, Enumerable.Empty<string>(), null);
                _m.RuntimeBindings.UnionWith(moduleLocals.AllLocals);
                _m.RuntimeBindings.UnionWith(moduleLocals.LocalFunctions);
                _m.RuntimeBindings.ExceptWith(_m.Functions);
                _m.RuntimeBindings.ExceptWith(_m.Classes.Keys);
                foreach (var name in _m.RuntimeBindings) _moduleFieldTypes[name] = "dynamic";
                _w.Line("private static global::Typhon.Runtime.ExecutionScope __typhon_execution;");
            }

            // free variables of functions/classes in this module → must be static fields, not Main locals
            var usedInDefs = new HashSet<string>();
            foreach (var s in body.Where(s => s is FunctionDef || s is ClassDef)) CollectFreeNames(s, usedInDefs);
            // globals() reads module names by string: every module-level name is a field then
            bool usesGlobals = false;
            AstWalker.VisitAll(body, n => { if (n is NameExpr { Id: "globals" }) usesGlobals = true; });
            bool exposesGlobals = usesGlobals || _m.WritesModuleGlobals || isEntryModule && _p.Modules.Values.Any(source => ReadsModuleRegistry(source.Ast.Body));
            _nativeImportsInNamespace = !runtimeCode && !_m.IsGdScript && exposesGlobals &&
                (_m.ConditionalImportBindings.Count > 0 || body.Any(statement => NativeNamespaceImports(statement).Any()));
            if (exposesGlobals)
                foreach (var s in body)
                    if (s is AssignStmt ga) foreach (var t in ga.Targets) foreach (var nm in NamesIn(t)) usedInDefs.Add(nm);
                    else if (s is AnnAssignStmt gaa && gaa.Target is NameExpr gan) usedInDefs.Add(gan.Id);

            FindFunctionAliases(body);
            var moduleAssignments = body.OfType<AssignStmt>()
                .Where(statement => statement.Targets.Count == 1 && statement.Targets[0] is NameExpr)
                .ToLookup(statement => ((NameExpr)statement.Targets[0]).Id);
            var fields = new Dictionary<string, string>();      // name → C# type
            var execStmts = new List<Stmt>();                     // static ctor (regular) / Main (main module)
            var mainBlocks = new List<Stmt>();

            if (!runtimeCode && !_m.IsGdScript)
            {
                if (_m.IsPackage && !_m.Globals.Contains("__path__"))
                {
                    fields["__path__"] = _moduleFieldTypes["__path__"] = "List<string>";
                    string directory = System.IO.Path.GetDirectoryName(System.IO.Path.GetFullPath(_m.Path));
                    _w.Line($"internal static List<string> __path__ = [{CsString(directory)}];");
                }
                foreach (var name in new[] { "__name__", "__doc__" }.Where(_m.Globals.Contains))
                {
                    fields[name] = _moduleFieldTypes[name] = "dynamic";
                    string initial = name == "__name__" ? CsString(_m.Name) : ModuleDocLiteral(body);
                    _w.Line($"internal static dynamic? {name} = {initial};");
                }
            }

            foreach (string name in _m.ReboundFunctions.Concat(_m.ReboundClasses).Distinct().OrderBy(name => name, StringComparer.Ordinal))
                EmitLateModuleField(name, fields);

            foreach (var conditionalClass in body.OfType<ClassDef>().Where(c => c.ConditionalModuleDefinition))
                _w.Line($"internal static bool {ClassActivation(conditionalClass)};");

            foreach (var s in body)
            {
                // defaults Python evaluates when the def / class statement runs: fields assigned at this position
                if (s is FunctionDef fdef) RegisterDefaultFields(fdef, null, fields, execStmts);
                if (s is ClassDef cdef) foreach (var m in cdef.Body.OfType<FunctionDef>()) RegisterDefaultFields(m, cdef.Name, fields, execStmts);
                if (s is ImportStmt || s is ImportFromStmt)
                {
                    bool HasLateBinding(string name) => _lateModuleFields.Contains(name) || _m.ConditionalGlobals.Contains(name);
                    if (ProjectImports(s).Any() || PlatformModules(s).Any() ||
                        NativeNamespaceImports(s).Any(binding => _nativeImportsInNamespace || _m.ConditionalImportBindings.Contains(binding.Binding)) ||
                        s is ImportStmt import && import.Names.Any(alias => HasLateBinding(alias.AsName ?? alias.Name.Split('.')[0])) ||
                        s is ImportFromStmt from && from.Names.Any(alias => HasLateBinding(alias.AsName ?? alias.Name)))
                        execStmts.Add(s);
                    continue;
                }
                if (s is FunctionDef || s is ClassDef)
                {
                    if (s is ClassDef definition && !definition.ConditionalModuleDefinition &&
                        definition != GdScriptClass && (RunsClassBodyAtDefinition(definition) || CapturesClassModuleName))
                        execStmts.Add(new ClassBodyInitialization { Definition = definition, Line = definition.Line, Col = definition.Col });
                    if (runtimeCode && s is not ClassDef { ConditionalModuleDefinition: true })
                    {
                        string name = s is FunctionDef df ? df.Name : ((ClassDef)s).Name;
                        execStmts.Add(new ExprStmt
                        {
                            Line = s.Line, Col = s.Col, Value = new CallExpr
                            {
                                Func = new NameExpr { Id = "__typhon_export" },
                                Args = { new Arg { Value = new ConstExpr { Kind = ConstKind.Str, Str = name } }, new Arg { Value = new NameExpr { Id = name } } },
                            },
                        });
                    }
                    continue;
                }
                if (s is PassStmt) continue;
                if (s is AssignStmt aliasStmt && aliasStmt.Targets.Count == 1 && aliasStmt.Targets[0] is NameExpr aliasName &&
                    _m.TypeAliases.ContainsKey(aliasName.Id) && !CanMaterializeTypeAlias(aliasStmt.Value))
                {
                    // After imports are resolved, uppercase names can be numeric flags rather than type names.
                    if (aliasStmt.Value is not BinOpExpr { Op: "|" } flags || !IsIntegerFlagValue(flags)) continue;
                    _m.TypeAliases.Remove(aliasName.Id);
                }
                if (s is AssignStmt fnAlias && fnAlias.Targets.Count == 1 && fnAlias.Targets[0] is NameExpr fnAliasName && _functionAliases.ContainsKey(fnAliasName.Id)) continue;
                if (s is AnnAssignStmt aliasAnn && aliasAnn.Target is NameExpr aliasAnnName && _m.TypeAliases.ContainsKey(aliasAnnName.Id)) continue;
                if (_m.RuntimeCodeMode != "single" && s is ExprStmt es && es.Value is ConstExpr ce &&
                    (ce.Kind == ConstKind.Str || ce.Kind == ConstKind.Ellipsis)) continue;
                if (!runtimeCode && !_m.Globals.Contains("__name__") && IsMainGuard(s))
                { mainBlocks.AddRange(((IfStmt)s).Body); continue; }

                string fieldName = null; Expr ann = null, value = null;
                if (s is AssignStmt a && a.Targets.Count == 1 && a.Targets[0] is NameExpr an) { fieldName = an.Id; value = a.Value; }
                else if (s is AnnAssignStmt aa && aa.Target is NameExpr aan) { fieldName = aan.Id; ann = aa.Annotation; value = aa.Value; }
                if (runtimeCode)
                {
                    execStmts.Add(s);
                    continue;
                }

                // remember the type of every module-level name (field or Main local) for later inference
                if (fieldName != null && !_moduleFieldTypes.ContainsKey(fieldName))
                {
                    string t = ann != null ? MapType(ann, s) : PyType(InferType(value));
                    if (t != null) _moduleFieldTypes[fieldName] = t;
                }

                bool makeField = fieldName != null && !fields.ContainsKey(fieldName) && (!isMainModule || usedInDefs.Contains(fieldName));
                if (makeField)
                {
                    // NAMES = [] filled later (appends anywhere in the module): typed by what is added, like a local list
                    string emptyType = null;
                    if (ann == null && value != null && TypeInference.IsEmptyContainer(value))
                    {
                        char ekind = TypeInference.ContainerKind(value);
                        _emptyModuleFields[fieldName] = ekind;
                        emptyType = EmptyContainerType(ModuleFieldKey(fieldName), ekind, value);
                        if (emptyType != null && (emptyType.Contains("dynamic") || emptyType.Contains(TypeInference.Pending) && !_dry)) emptyType = null;
                    }
                    string type = ann != null ? MapType(ann, s) : emptyType ?? (PyType(InferType(value)) ?? ImplicitDynamic(s, $"module variable '{fieldName}'"));
                    if (ann == null && type != "dynamic" && (_m.GlobalsReboundThroughNamespace.Contains(fieldName) ||
                        moduleAssignments[fieldName].Any(statement => statement != s && ModuleAssignmentChangesType(statement.Value, type))))
                        type = "dynamic";
                    fields[fieldName] = type;
                    _moduleFieldTypes[fieldName] = type;
                    string vis = SurfaceVisibility(fieldName.StartsWith("_") ? "internal" : "public", type);
                    LineDirective(s);
                    // a field initializer runs before the static constructor: only while no earlier module statement had to go
                    // there, else this assignment joins them, so the module runs top to bottom like Python's
                    if (!isMainModule && value != null && execStmts.Count == 0)
                    {
                        _globalsBeforeFieldInitializer = fields.Keys.Where(name => name != fieldName);
                        try
                        {
                            string initial = value is ComprehensionExpr comprehension && !TypeInference.IsNonePlaceholder(comprehension)
                                ? EmitComprehension(comprehension, type)
                                : type != "dynamic" ? EmitExpr(value, targetTyped: true) : EmitLooseValue(value);
                            _w.Line($"{vis} static {type} {Esc(fieldName)} = {Checked(initial)};");
                        }
                        finally { _globalsBeforeFieldInitializer = null; }
                    }
                    else
                    {
                        _w.Line($"{vis} static {type} {Esc(fieldName)};");
                        if (value != null) execStmts.Add(s);
                    }
                    continue;
                }
                // N, E, S, W = -10, 1, 10, -1 / a = b = 0: every name bound here that a def reads (or another module may
                // import) is a field too; the statement then assigns the fields
                if (s is AssignStmt multi && (multi.Targets.Count > 1 || multi.Targets[0] is TupleExpr || multi.Targets[0] is ListExpr))
                {
                    var bound = new Dictionary<string, string>();
                    foreach (var target in multi.Targets) UnpackedTypes(target, multi.Value, PyType(InferType(multi.Value)), bound);
                    bool declared = false;
                    foreach (var kv in bound)
                    {
                        if (kv.Value != null && !_moduleFieldTypes.ContainsKey(kv.Key)) _moduleFieldTypes[kv.Key] = kv.Value;
                        if (fields.ContainsKey(kv.Key) || (isMainModule && !usedInDefs.Contains(kv.Key))) continue;
                        string type = kv.Value ?? ImplicitDynamic(s, $"module variable '{kv.Key}'");
                        fields[kv.Key] = type;
                        _moduleFieldTypes[kv.Key] = type;
                        LineDirective(s);
                        _w.Line($"{SurfaceVisibility(kv.Key.StartsWith("_") ? "internal" : "public", type)} static {type} {Esc(kv.Key)};");
                        declared = true;
                    }
                    if (declared || bound.Keys.Any(fields.ContainsKey)) { execStmts.Add(s); continue; }
                }
                execStmts.Add(s);
            }
            if (!runtimeCode)
            {
                foreach (var name in _m.ConditionalGlobals.OrderBy(n => n, StringComparer.Ordinal))
                {
                    if (fields.ContainsKey(name) || isEntryModule && !exposesGlobals && !usedInDefs.Contains(name)) continue;
                    EmitLateModuleField(name, fields);
                }
            }
            if (fields.Count > 0) _w.Line();
            _moduleFieldNames.UnionWith(fields.Keys);
            if (Obs != null && !runtimeCode && !isMainModule && fields.Count > 0)
                Obs.Fields[TypeInference.ModuleFieldsKey(_m)] = fields;
            foreach (var binding in _runtimeProjectBindings.Values)
                _w.Line($"private static dynamic? {binding.Storage};");
            if (usesGlobals) _w.Line($"private static object __typhon_globals() => {EmitGlobals()};");

            foreach (var s in body)
            {
                if (s is FunctionDef f) { EmitFunction(f, isModuleLevel: true); _w.Line(); }
                else if (s is ClassDef c && c != GdScriptClass) { EmitClass(c); _w.Line(); }
            }
            foreach (var f in body.OfType<FunctionDef>())
                if (FunctionValueKeys.Contains(TypeInference.FuncKey(_m, null, f.Name))) { EmitFunctionValueClass(f); _w.Line(); }

            string abcMixins = RegisterAbcMixins();
            if (runtimeCode)
            {
                _scopeKey = RuntimeCodeScopeKey;
                if (CanFallThrough(execStmts)) execStmts.Add(new ReturnStmt { Value = new ConstExpr { Kind = ConstKind.None } });
                _w.Line("public static object? ExecutePythonCode(global::System.Collections.IDictionary globals, global::System.Collections.IDictionary locals)");
                EmitFunctionBody(execStmts, new Scope
                    { ReturnType = "dynamic", DisplaysExpressionValues = _m.RuntimeCodeMode == "single", ProfileName = "<module>", FunctionQualName = "<module>", ProfileLine = 1 },
                    fields.Keys.Concat(_m.RuntimeBindings),
                    prologue: "__typhon_execution = new global::Typhon.Runtime.ExecutionScope(globals, locals);" + abcMixins);
            }
            else if (isMainModule)
            {
                var all = new List<Stmt>(execStmts);
                all.AddRange(mainBlocks);
                EmitMain(all, fields.Keys, body.FirstOrDefault(), abcMixins);
            }
            else
            {
                // A package module initializes at the import statement, including when its
                // entire module body consists of C# field initializers.
                if (execStmts.Count > 0 || abcMixins.Length != 0 || IsProjectPackageModule(_m))
                {
                    _scopeKey = TypeInference.FuncKey(_m, null, "<module>");
                    _w.Line("static " + Esc(_m.ClassName) + "()");
                    EmitFunctionBody(execStmts, new Scope { ReturnType = "void" }, fields.Keys, prologue: abcMixins);
                    _w.Line();
                }
                if (mainBlocks.Count > 0 && (_p.MainModule == null || _p.MainModule == _m.Name)) EmitMain(mainBlocks, fields.Keys, body.First(IsMainGuard));
            }
        }

        void EmitLateModuleField(string name, Dictionary<string, string> fields)
        {
            const string moduleType = "global::Typhon.Runtime.PyModule";
            string storage = "__typhon_" + NewTmp("module");
            fields.Add(name, "dynamic");
            _moduleFieldTypes[name] = "dynamic";
            _lateModuleFields.Add(name);
            _w.Line($"private static object? {storage} = {moduleType}.Unbound;");
            _w.Line("[global::Typhon.Runtime.PyLateAttribute]");
            _w.Line($"{(name.StartsWith("_") ? "internal" : "public")} static dynamic? {Esc(name)} " +
                $"{{ get => {moduleType}.ReadLateGlobal({storage}, {CsString(name)}); set => {storage} = value; }}");
        }

        string RegisterAbcMixins()
        {
            var registration = new System.Text.StringBuilder();
            foreach (var mixin in _p.MixedInto)
            {
                ClassDef ancestor = mixin.Key;
                if (ancestor.TypeParams.Count != 0 || !HasVirtualSubclasses(ancestor)) continue;
                var owner = _p.Modules.Values.FirstOrDefault(module => module.Classes.TryGetValue(ancestor.Name, out var declared) && declared == ancestor);
                if (owner == null) continue;
                foreach (var copy in mixin.Value)
                {
                    if (copy.Module != _m || copy.Class.TypeParams.Count != 0) continue;
                    registration.Append($"\n{Rt("__register_mixin_base")}(typeof({ModuleClassName(owner)}.{Esc(ancestor.Name)}), typeof({Esc(copy.Class.Name)}));");
                }
            }
            return registration.ToString();
        }

        string RuntimeCodeScopeKey => TypeInference.FuncKey(_m, null, "<runtime code>");

        /// <summary>Module fields that start as an empty container (their element types come from what the module adds).</summary>
        readonly Dictionary<string, char> _emptyModuleFields = new Dictionary<string, char>();
        bool ModuleAssignmentChangesType(Expr value, string initialType)
        {
            if (IsNone(value)) return IsValueTypeName(initialType) && !initialType.EndsWith("?");
            if (IsEmptyLiteral(value)) return false;
            string type = PyType(InferType(value));
            return type != TypeInference.Pending && type != initialType;
        }

        string ModuleFieldKey(string name) => _m.Name + "|module." + name;

        /// <summary>The module's static fields (module-level variables functions can see).</summary>
        readonly HashSet<string> _moduleFieldNames = new HashSet<string>();
        IEnumerable<string> _globalsBeforeFieldInitializer;
        readonly HashSet<string> _lateModuleFields = new HashSet<string>();

        readonly HashSet<TupleExpr> _identityTuples = new HashSet<TupleExpr>();

        // A module tuple used as an identity sentinel needs the same object each time it is read.
        void FindIdentityTuples(List<Stmt> body)
        {
            var tuples = body.OfType<AssignStmt>()
                .Where(a => a.Value is TupleExpr tuple && !tuple.Elts.Any(item => item is StarredExpr))
                .SelectMany(a => a.Targets.OfType<NameExpr>().Select(name => (name.Id, Tuple: (TupleExpr)a.Value)))
                .ToLookup(a => a.Id, a => a.Tuple);
            if (tuples.Count == 0) return;

            AstWalker.VisitAll(body, node =>
            {
                if (node is not CompareExpr comparison) return;
                Expr left = comparison.Left;
                for (int i = 0; i < comparison.Ops.Count; i++)
                {
                    Expr right = comparison.Comparators[i];
                    if (comparison.Ops[i] is "is" or "is not" && !IsNone(left) && !IsNone(right))
                    {
                        if (left is NameExpr leftName) _identityTuples.UnionWith(tuples[leftName.Id]);
                        if (right is NameExpr rightName) _identityTuples.UnionWith(tuples[rightName.Id]);
                    }
                    left = right;
                }
            });
        }

        /// <summary>Reading sys.modules can expose the entry module's globals by name, including to another module.</summary>
        static bool ReadsModuleRegistry(List<Stmt> body)
        {
            var aliases = new HashSet<string>();
            bool readsRegistry = false;
            AstWalker.VisitAll(body, node =>
            {
                if (node is ImportStmt imported)
                    foreach (var name in imported.Names)
                        if (name.Name == "sys") aliases.Add(name.AsName ?? name.Name);
                if (node is ImportFromStmt from && from.Level == 0 && from.Module == "sys" && from.Names.Any(name => name.Name == "modules" || name.Name == "*"))
                    readsRegistry = true;
            });
            if (aliases.Count > 0 && !readsRegistry)
                AstWalker.VisitAll(body, node =>
                {
                    if (node is AttributeExpr { Name: "modules", Target: NameExpr sys } && aliases.Contains(sys.Id)) readsRegistry = true;
                });
            return readsRegistry;
        }

        /// <summary>globals(): the module's names and values (fields, classes, functions used as values), read when called.</summary>
        string EmitGlobals()
        {
            if (_m.RuntimeCodeMode != null) return "((dynamic)__typhon_execution.Globals)";
            if (_m.WritesModuleGlobals || _nativeImportsInNamespace || _lateModuleFields.Count != 0)
                return $"((dynamic)global::Typhon.Runtime.PyModule.Of(typeof({ModuleClassName(_m)}), {CsString(_m.Name)}).__dict__)";
            var entries = new List<string>();
            var fields = _globalsBeforeFieldInitializer ?? _moduleFieldNames.OrderBy(x => x, StringComparer.Ordinal);
            if (_m.IsGdScript) entries.Add($"[\"__name__\"] = {CsString(_m.Name)}");
            else
                foreach (var name in new[] { "__name__", "__doc__" }.Where(name => !fields.Contains(name)))
                    entries.Add($"[{CsString(name)}] = {ModuleObject(_m)}.{name}");
            foreach (var f in fields) entries.Add($"[{CsString(f)}] = {Esc(f)}");
            foreach (var entry in _m.Classes.OrderBy(pair => pair.Key, StringComparer.Ordinal))
                entries.Add($"[{CsString(entry.Key)}] = {ClassTypeValue(Esc(entry.Key), entry.Value)}");
            foreach (var fn in _m.Ast.Body.OfType<FunctionDef>())
                if (FunctionValueKeys.Contains(TypeInference.FuncKey(_m, null, fn.Name))) entries.Add($"[{CsString(fn.Name)}] = {FunctionValueType(_m, fn.Name)}.Instance");
            return $"new OrderedDictionary<string, object?> {{ {string.Join(", ", entries)} }}";
        }

        string EmitLocals()
        {
            if (_scope == null || _scopeKey == TypeInference.FuncKey(_m, null, "<main>") ||
                _scopeKey == TypeInference.FuncKey(_m, null, "<module>")) return EmitGlobals();
            var names = new HashSet<string>(_scope.Params);
            if (_scope.Locals != null)
                foreach (var block in _blocks)
                    names.UnionWith(block.Declared.Where(_scope.Locals.AllLocals.Contains));
            var values = names.OrderBy(name => name, StringComparer.Ordinal)
                .Select(name => $"[{CsString(name)}] = {EmitName(new NameExpr { Id = name })}");
            return $"new OrderedDictionary<string, object?> {{ {string.Join(", ", values)} }}";
        }

        /// <summary>The type each name in an assignment target gets (null: unknown): a, (b, c) = 1, (2.0, "x"); x, y = point; i, j = range(2).</summary>
        void UnpackedTypes(Expr target, Expr value, string valueType, Dictionary<string, string> into)
        {
            switch (target)
            {
                case NameExpr n:
                    into[n.Id] = TypeInference.IsUnknown(valueType) || valueType == TypeInference.Pending ? null : valueType;
                    return;
                case TupleExpr _:
                case ListExpr _:
                {
                    var elts = target is TupleExpr te ? te.Elts : ((ListExpr)target).Elts;
                    var values = value is TupleExpr vt && vt.Elts.Count == elts.Count ? vt.Elts : value is ListExpr vl && vl.Elts.Count == elts.Count ? vl.Elts : null;
                    var parts = values?.Select(v => PyType(InferType(v))).ToList() ?? TupleElementTypes(valueType);
                    for (int i = 0; i < elts.Count; i++)
                    {
                        if (elts[i] is StarredExpr st) { foreach (var name in NamesIn(st.Value)) into[name] = null; continue; }
                        string part = parts != null && parts.Count == elts.Count ? parts[i] : valueType != null ? ElementTypeOf(valueType) : null;
                        UnpackedTypes(elts[i], values?[i], part, into);
                    }
                    return;
                }
                default: return; // attributes / subscripts bind no names
            }
        }

        static void CollectFreeNames(Stmt s, HashSet<string> into)
        {
            if (s is FunctionDef f)
            {
                var loc = LocalsAnalyzer.Analyze(f.Body, f.Params.Select(p => p.Name), null);
                into.UnionWith(loc.Globals);
                var bound = new HashSet<string>(loc.AllLocals);
                bound.UnionWith(f.Params.Select(p => p.Name));
                bound.UnionWith(loc.LocalFunctions);
                foreach (var n in AllNodes(f.Body))
                    if (n is NameExpr ne && (!bound.Contains(ne.Id) || loc.Globals.Contains(ne.Id))) into.Add(ne.Id);
                foreach (var p in f.Params) AstWalker.VisitAll(p.Default, n => { if (n is NameExpr ne) into.Add(ne.Id); });
            }
            else if (s is ClassDef c)
            {
                foreach (var st in c.Body)
                {
                    if (st is FunctionDef || st is ClassDef) CollectFreeNames(st, into);
                    else AstWalker.VisitAll(st, n => { if (n is NameExpr ne) into.Add(ne.Id); });
                }
            }
        }

        void EmitMain(List<Stmt> stmts, IEnumerable<string> moduleFields, Node at, string registrations = "")
        {
            var scope = new Scope { ReturnType = "void", ModuleTraceScope = true };
            var locals = LocalsAnalyzer.Analyze(stmts, Enumerable.Empty<string>(), moduleFields);
            bool isAsync = locals.HasAwait;
            LineDirective(at);
            _scopeKey = TypeInference.FuncKey(_m, null, "<main>");
            EmitAttributes(ApartmentAttributes());
            _w.Line(isAsync ? "public static async Task Main(string[] __argv)" : "public static void Main(string[] __argv)");
            scope.IsAsync = isAsync;
            // an uncaught SystemExit (sys.exit) ends the program with its code, without a traceback
            string tests = PytestEpilogue();
            foreach (ModuleInfo module in _p.Modules.Values.Where(module => module.UsedByDynamicImport))
                registrations += $"\nglobal::Typhon.Runtime.PyModule.RegisterCompiled({CsString(module.Name)}, typeof({ModuleClassName(module)}));";
            EmitFunctionBody(stmts, scope, moduleFields, locals, prologue: $"global::Typhon.Stdlib.sys_.__init__(__argv, typeof({ModuleClassName(_m)}));{registrations}\ntry\n{{",
                             epilogue: (tests != null ? tests + "\n" : "") + "}\ncatch (global::Typhon.Runtime.SystemExit __exit) { __exit.Exit(); }");
        }

        /// <summary>
        /// @STAThread / @MTAThread on a function of the module also mark the generated Main: the CLR reads the COM apartment of
        /// the main thread only from the entry point, which Typhon writes itself (Windows Forms, WPF and WinUI need an STA thread).
        /// </summary>
        List<Expr> ApartmentAttributes()
        {
            var seen = new HashSet<string>();
            var found = new List<Expr>();
            foreach (var f in _m.Ast.Body.OfType<FunctionDef>())
                foreach (var d in f.Decorators)
                {
                    string name = d is CallExpr ? null : DecoratorName(d)?.Split('.').Last();
                    if (name == "STAThreadAttribute" || name == "MTAThreadAttribute") name = name.Substring(0, name.Length - "Attribute".Length);
                    if ((name == "STAThread" || name == "MTAThread") && seen.Add(name)) found.Add(d);
                }
            return found;
        }


        /// <summary>
        /// A test module (it imports pytest): after its body, `typhon test` runs its test_* functions and Test* classes, in
        /// the order they are defined.
        /// </summary>
        string PytestEpilogue()
        {
            const string Meta = "Typhon.Stdlib.pytest";
            if (!_staticTypes.Contains(Meta) && !_dotnetAliases.ContainsValue(Meta)) return null;
            // (name, value): a decorated function's value (a test with marks, a fixture), null for a plain def or a Test class
            var entries = new List<string>();
            foreach (var s in _m.Ast.Body)
            {
                if (s is FunctionDef f && f.PyName != null) entries.Add($"({CsString(f.PyName)}, (object?){EmitName(new NameExpr { Id = f.PyName })})");
                else if (s is FunctionDef pf && pf.Name.StartsWith("test")) entries.Add($"({CsString(pf.Name)}, null)");
                else if (s is ClassDef c && c.Name.StartsWith("Test")) entries.Add($"({CsString(c.Name)}, null)");
            }
            return $"global::Typhon.Stdlib.pytest.__run_module(typeof({ModuleClassName(_m)}), {CsString(System.IO.Path.GetFileName(_path))}, new (string, object?)[] {{ {string.Join(", ", entries)} }});";
        }

        void EmitDocComment(List<Stmt> body)
        {
            if (body.Count == 0 || !(body[0] is ExprStmt es) || !(es.Value is ConstExpr c) || c.Kind != ConstKind.Str) return;
            var lines = c.Str.Replace("\r", "").Trim('\n').Split('\n');
            int indent = lines.Skip(1).Where(l => l.Trim().Length > 0).Select(l => l.Length - l.TrimStart().Length).DefaultIfEmpty(0).Min();
            _w.Line("/// <summary>");
            for (int i = 0; i < lines.Length; i++)
            {
                string l = i == 0 ? lines[i].Trim() : (lines[i].Length >= indent ? lines[i].Substring(indent) : lines[i].Trim());
                _w.Line("/// " + System.Security.SecurityElement.Escape(l));
            }
            _w.Line("/// </summary>");
        }

